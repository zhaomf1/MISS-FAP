#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""将可读的 UTF-8 UI 文案表转换为 ARMCC 5 兼容的 C 宏头文件。"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


DEFINE_RE = re.compile(
    r'^\s*#define\s+(S_[A-Z0-9_]+)\s+"((?:[^"\\]|\\.)*)"'
    r'(?:\s*/\*\s*(.*?)\s*\*/)?\s*$'
)
NAME_RE = re.compile(r"^S_[A-Z0-9_]+$")


def escape_c_string(value: str) -> str:
    r"""将 UTF-8 字节转成独立的 \xNN，避免 C 十六进制转义连续吞字符。"""
    encoded = value.encode("utf-8")
    parts: list[str] = []
    for byte in encoded:
        if byte == 0x22:
            parts.append(r'\"')
        elif byte == 0x5C:
            parts.append(r"\\")
        elif 0x20 <= byte <= 0x7E:
            parts.append(chr(byte))
        else:
            parts.append(f"\\x{byte:02X}")
    return '"' + "".join(parts) + '"'


def parse_source(source: str) -> list[tuple[str, str, str]]:
    """读取 #define S_NAME "文案" /* 注释 */ 格式，每行一条。"""
    entries: list[tuple[str, str, str]] = []
    seen: set[str] = set()
    for line_number, line in enumerate(source.splitlines(), start=1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#") and not stripped.startswith("#define"):
            continue
        if stripped.startswith("//"):
            continue
        match = DEFINE_RE.match(line)
        if not match:
            escaped_line = line.encode("unicode_escape").decode("ascii")
            raise ValueError(f"Invalid format on line {line_number}: {escaped_line}")
        name, value, comment = match.groups()
        if not NAME_RE.fullmatch(name):
            raise ValueError(f"Invalid macro name on line {line_number}: {name}")
        if name in seen:
            raise ValueError(f"Duplicate macro on line {line_number}: {name}")
        if not value:
            raise ValueError(f"Empty string on line {line_number}: {name}")
        seen.add(name)
        entries.append((name, value, comment or ""))
    if not entries:
        raise ValueError("No S_* macro definitions found")
    return entries


def generate_header(entries: list[tuple[str, str, str]]) -> str:
    """生成只包含 ASCII 字符的 C 头文件。"""
    lines = [
        "/* Generated by tools/generate_ui_strings.py; do not edit manually. */",
        "#ifndef UI_STRINGS_GENERATED_H",
        "#define UI_STRINGS_GENERATED_H",
        "",
        "/* UTF-8 byte escapes keep string literals compatible with ARMCC 5. */",
    ]
    for name, value, comment in entries:
        line = f"#define {name:<24} {escape_c_string(value)}"
        lines.append(line)
    lines.extend(["", "#endif /* UI_STRINGS_GENERATED_H */", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate ARMCC-compatible UI string macros")
    parser.add_argument("source", type=Path, help="UTF-8 UI string source file")
    parser.add_argument("output", type=Path, help="Generated C header path")
    args = parser.parse_args()

    try:
        source = args.source.read_text(encoding="utf-8-sig")
        entries = parse_source(source)
        result = generate_header(entries)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(result, encoding="ascii", newline="\n")
    except (OSError, UnicodeError, ValueError) as exc:
        parser.error(str(exc))

    print(f"Generated {len(entries)} UI strings: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
